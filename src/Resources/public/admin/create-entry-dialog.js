/*
 * The create dialog of the Content hub (docs/spec/admin.md#create-dialog), which admin/entry/_create_dialog.html.twig
 * renders with the button that opens it ([data-cms-create-entry], whose aria-controls names the dialog).
 *
 * A button that's a link opens the dialog at its content type's create form, which the dialog loads from the link.
 * Otherwise the dialog asks for the content type first, and loads the form of the one picked. The form posts as any
 * form does: the server opens the builder, or shows the form with its errors as a page.
 *
 * In the form, here or on that page, the slug follows the title, generated by the server with Sylius's slug generator,
 * until the editor changes it.
 */

const SLUG_DELAY = 250;

/** Counts the loads of each dialog, so only the last one picked fills it */
const loads = new WeakMap();

document.addEventListener('click', (event) => {
    if (!(event.target instanceof Element)) {
        return;
    }

    const opener = event.target.closest('[data-cms-create-entry]');
    if (opener !== null) {
        const dialog = document.getElementById(opener.getAttribute('aria-controls') ?? '');
        if (dialog instanceof HTMLDialogElement) {
            event.preventDefault();
            open(dialog, opener.getAttribute('href'));
        }

        return;
    }

    const dialog = event.target.closest('dialog');
    if (dialog === null) {
        return;
    }

    const type = event.target.closest('[data-cms-create-entry-type]');
    if (type !== null) {
        event.preventDefault();
        load(dialog, type.getAttribute('href') ?? '');
    } else if (event.target.closest('[data-cms-create-entry-back]') !== null) {
        pickContentType(dialog);
    } else if (event.target.closest('[data-cms-dialog-close]') !== null) {
        dialog.close();
    }
});

// The create page's own form
document.querySelectorAll('[data-cms-create-entry-form]').forEach(fillSlugFromTitle);

/**
 * Opens the dialog at the form of the link's content type, or else at the content types to pick from
 */
function open(dialog, url) {
    dialog.showModal();

    if (url === null) {
        pickContentType(dialog);
    } else {
        load(dialog, url);
    }
}

function pickContentType(dialog) {
    loads.set(dialog, (loads.get(dialog) ?? 0) + 1);
    const step = dialog.querySelector('[data-cms-create-entry-step="content_type"]');
    step.hidden = false;
    dialog.querySelector('[data-cms-create-entry-step="form"]').hidden = true;
    dialog.setAttribute('aria-labelledby', step.querySelector('h2').id);
    step.querySelector('[data-cms-create-entry-type]')?.focus();
}

/**
 * Loads a content type's create form into the dialog, then puts the focus in its title
 */
async function load(dialog, url) {
    const ticket = (loads.get(dialog) ?? 0) + 1;
    loads.set(dialog, ticket);

    const typeStep = dialog.querySelector('[data-cms-create-entry-step="content_type"]');
    if (typeStep !== null) {
        typeStep.hidden = true;
    }

    dialog.querySelector('[data-cms-create-entry-step="form"]').hidden = false;
    const content = dialog.querySelector('[data-cms-create-entry-content]');
    content.innerHTML = '<div class="ui active centered inline loader"></div>';

    let html;
    try {
        const response = await fetch(url, { headers: { 'X-Requested-With': 'XMLHttpRequest' }, credentials: 'same-origin' });
        html = response.ok ? await response.text() : null;
    } catch {
        html = null;
    }

    if (loads.get(dialog) !== ticket) {
        return;
    }

    if (html === null) {
        const message = document.createElement('p');
        message.className = 'ui negative message';
        message.textContent = dialog.dataset.loadFailed ?? '';
        content.replaceChildren(message);

        return;
    }

    content.innerHTML = html;
    const heading = content.querySelector('[data-cms-create-entry-heading]');
    if (heading !== null) {
        heading.id = `${dialog.id}-form-heading`;
        dialog.setAttribute('aria-labelledby', heading.id);
    }

    const form = content.querySelector('[data-cms-create-entry-form]');
    if (form !== null) {
        fillSlugFromTitle(form);
        form.querySelector('[data-cms-create-entry-title]')?.focus();
    }
}

/**
 * Fills the slug from the title while the editor types it, until the editor changes the slug. A slug already there,
 * such as one sent back with an error, is the editor's
 */
function fillSlugFromTitle(form) {
    const title = form.querySelector('[data-cms-create-entry-title]');
    const slug = form.querySelector('[data-cms-create-entry-slug]');
    if (title === null || slug === null) {
        return;
    }

    let edited = slug.value !== '';
    let timer;
    let request = 0;

    slug.addEventListener('input', () => {
        // Emptying the slug lets it follow the title again
        edited = slug.value !== '';
    });

    title.addEventListener('input', () => {
        if (edited) {
            return;
        }

        clearTimeout(timer);
        timer = setTimeout(async () => {
            const current = ++request;
            const url = new URL(slug.dataset.cmsCreateEntrySlug, window.location.href);
            url.searchParams.set('title', title.value);

            try {
                const response = await fetch(url, { headers: { Accept: 'application/json' }, credentials: 'same-origin' });
                const { slug: generated } = await response.json();
                if (current === request && !edited && typeof generated === 'string') {
                    slug.value = generated;
                }
            } catch {
                // The server generates the slug of a form sent without one
            }
        }, SLUG_DELAY);
    });
}
